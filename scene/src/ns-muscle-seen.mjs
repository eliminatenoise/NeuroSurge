/** The table as contacts (pure): Map key -> Map(neighbour key -> samples), symmetric. */
export function seenContactMap(list = MUSCLE_SEEN_CONTACTS) {
  const m = new Map();
  const add = (a, b, w) => { let r = m.get(a); if (!r) m.set(a, (r = new Map())); r.set(b, Math.max(r.get(b) || 0, w)); };
  for (const [a, b, w] of list) if (a !== b && Number.isFinite(w) && w > 0) { add(a, b, w); add(b, a, w); }
  return m;
}
/** The light the pictures show on the two sides of each pair (pure): Map key -> Map(neighbour key -> [[light on the
 * key, light on the neighbour], ...]), shade factors (1 = the full light), symmetric (the other way round, the two
 * numbers change places). A pair without samples is left out. */
export function seenLightMap(list = MUSCLE_SEEN_CONTACTS) {
  const m = new Map();
  const add = (a, b, v) => { let r = m.get(a); if (!r) m.set(a, (r = new Map())); r.set(b, v); };
  for (const [a, b, , light] of list) {
    if (a === b || !Array.isArray(light)) continue;
    const s = light.filter(q => Array.isArray(q) && q[0] > 0 && q[1] > 0);
    if (!s.length) continue;
    add(a, b, s.map(q => [q[0] / 100, q[1] / 100])); add(b, a, s.map(q => [q[1] / 100, q[0] / 100]));
  }
  return m;
}
