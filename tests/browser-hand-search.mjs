import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {once} from 'node:events';
import {fileURLToPath} from 'node:url';
import {createHandler, HOST} from '../serve-local.mjs';
const {chromium}=await import(process.env.NS_PLAYWRIGHT_MODULE || 'playwright');
const root=fileURLToPath(new URL('../',import.meta.url)), allowedHosts=new Set();
const server=createServer(createHandler({root,allowedHosts})).listen(0,HOST);
await once(server,'listening');
const address=HOST+':'+server.address().port;allowedHosts.add(address);
let browser;
try {
  const args=['--disable-background-networking'];
  if(process.env.NS_ANGLE) args.push('--use-angle='+process.env.NS_ANGLE);
  browser=await chromium.launch({executablePath:process.env.NS_CHROMIUM,args});
  const page=await browser.newPage({viewport:{width:1280,height:850}});
  const errors=[], addressBase='http://'+address;
  page.on('pageerror',e=>errors.push(String(e)));
  const requests=[];page.on('request',r=>requests.push(r.url()));
  await page.addInitScript(()=>{window.handMediaCalls=0;Object.defineProperty(navigator.mediaDevices,'getUserMedia',{value(){window.handMediaCalls++;return Promise.reject(Error('No device'));}});});
  await page.goto(addressBase+'/');
  await page.waitForFunction(()=>window.__nsQA?.inspect()?.features?.bodyRig && document.querySelector('#ns-app')?.dataset.nsPhase==='playing',null,{timeout:120000});
  assert.equal(requests.some(u=>u.includes('/assets/hand-search/')),false);
  await page.locator('#ns-canvas').click({position:{x:400,y:300}});
  await page.keyboard.press('f');const input=page.getByRole('textbox',{name:'Move the body'});
  await input.fill('press the button');await page.getByRole('button',{name:'Find hand recording'}).click();
  const hand=page.locator('#ns-act-hand');await hand.locator('[data-hand-ready]').waitFor();
  const rows=hand.locator('[data-hand-rows] tr');
  assert.equal(await rows.count(),5);
  assert.equal(await rows.first().locator('button').getAttribute('data-segment'),'R031-12July-SmallPrinter:68');
  const replay=hand.locator('.handReplay');assert.match(await replay.locator('[data-k=time]').innerText(),/42\.6/);
  await hand.locator('[data-hand-input]').fill('qzxvw');await hand.locator('[data-hand-input]').press('Enter');
  assert.equal(await hand.locator('[data-hand-ranking]').isVisible(),false);
  assert.equal(await hand.locator('[data-hand-replay]').isVisible(),false);
  await hand.locator('[data-hand-segment]').selectOption('R031-12July-SmallPrinter:25');
  assert.equal(await replay.locator('[data-k=pick]').inputValue(),'R031-12July-SmallPrinter:25');
  await page.keyboard.press('Escape');await page.keyboard.press('m');await page.getByRole('button',{name:'Hand search',exact:true}).click();
  await hand.locator('[data-hand-ready]').waitFor();await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'ns-canvas');
  assert.equal(await page.evaluate(()=>window.handMediaCalls),0);
  assert.ok(requests.every(u=>u.startsWith(addressBase+'/')));assert.deepEqual(errors,[]);
  console.log('F and M opened the same five-interval hand gallery, unknown words cleared the prior hand, and returning restored game focus.');
} finally {await browser?.close();await new Promise(resolve=>server.close(resolve));}
