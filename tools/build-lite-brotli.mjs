#!/usr/bin/env node
// Bundle the pinned upstream browser decoder without running package scripts.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [archive, base64, apache, mode] = process.argv.slice(2);
assert.ok(archive && base64 && apache && (!mode || mode === '--check'),
  'Usage: node tools/build-lite-brotli.mjs brotli-1.3.3.tgz base64-js-1.5.1.tgz Apache-2.0.txt [--check]');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
assert.equal(hash(readFileSync(archive)), '3c7c260f6263df95fee49a9119e9fd21227d628b6c9d99080a75edfd9e2bdb24');
assert.equal(hash(readFileSync(base64)), 'b1b7a945b52685269083425216d6597e33d97bf21699d656e92fdb3eb5210a85');
const get = (tarball, path) => execFileSync('tar', ['-xOf', tarball, `package/${path}`], {encoding:'utf8'});
const sources = ['bit_reader','context','decode','dictionary','dictionary-browser','dictionary.bin',
  'huffman','prefix','streams','transform'].map(name => `dec/${name}.js`);
const entries = sources.map(path => [path,get(archive,path)]);
entries.push(['base64-js',get(base64,'index.js')]);

const module = `// Generated by tools/build-lite-brotli.mjs from brotli@1.3.3 and base64-js@1.5.1.
// Copyright and licence notices: BROTLI-THIRD-PARTY.txt.
// Upstream sources are wrapped for browser module loading. No network or eval is used here.
const factories = {
${entries.map(([name,text]) => `${JSON.stringify(name)}: (module, exports, require) => {\n${text}\n}`).join(',\n')}
};
const cache = new Map();
function load(name) {
  if (cache.has(name)) return cache.get(name).exports;
  if (!Object.hasOwn(factories, name)) throw new Error('Unknown Brotli module: ' + name);
  const record = {exports:{}};
  cache.set(name, record);
  factories[name](record, record.exports, dependency => {
    if (dependency === 'base64-js') return load(dependency);
    if (!dependency.startsWith('./')) throw new Error('Unknown Brotli dependency: ' + dependency);
    const normalized = 'dec/' + dependency.slice(2);
    const file = normalized.endsWith('.js') ? normalized : normalized + '.js';
    return load(file === 'dec/dictionary-data.js' ? 'dec/dictionary-browser.js' : file);
  });
  return record.exports;
}
const decompress = load('dec/decode.js').BrotliDecompressBuffer;

/** The caller has already verified the compressed bytes and the exact decoded extent against the pack index. */
export function decodeLiteBrotli(bytes, expectedBytes) {
  if (!(bytes instanceof Uint8Array) || !Number.isSafeInteger(expectedBytes) || expectedBytes < 1) {
    throw new TypeError('Use verified Brotli bytes and their exact decoded length');
  }
  const decoded = decompress(bytes, expectedBytes);
  if (decoded.length !== expectedBytes) throw new Error('The Lite pack decoded to a different length');
  return decoded;
}
`;
const notice = `NeuroSurge Lite includes the browser decoder from Brotli.js 1.3.3.

Upstream project: https://github.com/devongovett/brotli.js
Pinned registry archive: https://registry.npmjs.org/brotli/-/brotli-1.3.3.tgz
Archive SHA-256: 3c7c260f6263df95fee49a9119e9fd21227d628b6c9d99080a75edfd9e2bdb24

The decoder adapts work Copyright 2013 Google Inc. The original Apache-2.0
source notices remain in the bundled module. Brotli.js is distributed through
npm with MIT metadata. NeuroSurge wraps the ten selected decoder and dictionary
modules to load as one JavaScript module, uses the upstream browser dictionary
path, and adds the check of the expected decoded length.

${readFileSync(apache,'utf8').trim()}

The module also includes base64-js 1.5.1 by Jameson Little.
Upstream project: https://github.com/beatgammit/base64-js
Pinned registry archive: https://registry.npmjs.org/base64-js/-/base64-js-1.5.1.tgz
Archive SHA-256: b1b7a945b52685269083425216d6597e33d97bf21699d656e92fdb3eb5210a85

${get(base64,'LICENSE').trim()}
`;
for (const [path, text] of [['lite/brotli.mjs', module], ['lite/BROTLI-THIRD-PARTY.txt', notice]]) {
  const file = resolve(root, path);
  if (mode === '--check') assert.equal(readFileSync(file, 'utf8'), text, path);
  else writeFileSync(file, text);
  console.log(path, Buffer.byteLength(text), hash(text));
}
