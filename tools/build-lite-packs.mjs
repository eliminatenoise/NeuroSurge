#!/usr/bin/env node
// Recompress the approved Full mesh packs for Lite without changing any decoded mesh bytes.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {brotliCompressSync, brotliDecompressSync, constants, gunzipSync} from 'node:zlib';
import {decodePack, validatePackIndex, packIndexRig, PACK_INDEX_SHA256} from '../scene/src/ns-pack.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const full = resolve(repo, 'packs');
const lite = resolve(repo, 'lite/packs');
const check = process.argv.includes('--check');
assert.ok(process.argv.slice(2).every(arg => arg === '--check'));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const start = performance.now();

const indexBytes = readFileSync(resolve(full, 'PACK-INDEX.json'));
assert.equal(sha(indexBytes), PACK_INDEX_SHA256, 'Full pack index changed');
const fullIndex = JSON.parse(indexBytes);
const fullPacks = validatePackIndex(fullIndex);
const rig = packIndexRig(fullIndex);
assert.ok(rig);
const rigBytes = readFileSync(resolve(full, rig.file));
assert.equal(rigBytes.length, rig.bytes, 'Full rig extent changed');
assert.equal(sha(rigBytes), rig.sha256, 'Full rig identity changed');

const output = new Map([[rig.file, rigBytes]]);
const report = [];
const next = fullIndex.packs.map((entry, number) => {
  const pack = fullPacks[number];
  const fullBytes = readFileSync(resolve(full, pack.file));
  assert.equal(fullBytes.length, pack.bytes, `${pack.name} extent`);
  assert.equal(sha(fullBytes), pack.sha256, `${pack.name} source identity`);
  const raw = gunzipSync(fullBytes);
  assert.equal(raw.length, entry.rawBytes, `${pack.name} decoded extent`);
  const compressed = brotliCompressSync(raw, {
    params: {
      [constants.BROTLI_PARAM_QUALITY]: 11,
      [constants.BROTLI_PARAM_SIZE_HINT]: raw.byteLength,
    },
  });
  const roundtrip = brotliDecompressSync(compressed);
  assert.deepEqual(roundtrip, raw, `${pack.name} decoded bytes changed`);
  const decoded = decodePack(roundtrip);
  assert.equal(decoded.name, pack.name);
  assert.equal(decoded.licence, entry.licence);
  assert.deepEqual([...decoded.meshes.keys()], pack.keys);
  const triangles = [...decoded.meshes.values()].reduce((sum, {mesh}) => sum + mesh.indices.length / 3, 0);
  assert.equal(triangles, entry.triangles);
  assert.ok(compressed.length < fullBytes.length, `${pack.name} Lite transport must be smaller`);
  output.set(pack.file, compressed);
  report.push({name: pack.name, keys: pack.files, triangles, fullBytes: fullBytes.length,
    liteBytes: compressed.length, decodedSha256: sha(raw)});
  return {...entry, bytes: compressed.length, sha256: sha(compressed)};
});

const index = {
  ...fullIndex,
  note: 'The same mesh-pack bytes and body rig as Full after decoding. This edition uses lossless Brotli transport. Source packets and asset licence terms are unchanged.',
  transport: {codec:'brotli', fullIndexSha256:PACK_INDEX_SHA256},
  packs: next,
};
validatePackIndex(index);
const encoded = Buffer.from(JSON.stringify(index, null, 1) + '\n');
output.set('PACK-INDEX.json', encoded);
const pin = sha(encoded);
const exporter = Buffer.from(`// Generated by tools/build-lite-packs.mjs; do not edit.\nexport const LITE_PACK_INDEX_SHA256 = '${pin}';\n`);

function put(file, bytes) {
  if (check) {
    assert.deepEqual(readFileSync(file), bytes, `${file} is stale`);
  } else {
    writeFileSync(file, bytes);
  }
}

if (!check) mkdirSync(lite, {recursive:true});
for (const [file, bytes] of output) put(resolve(lite, file), bytes);
put(resolve(repo, 'lite/asset-pin.mjs'), exporter);
console.log(JSON.stringify({
  state: check ? 'exact_lite_transport_rebuild_verified' : 'exact_lite_transport_generated',
  node: process.version,
  fullIndexSha256: PACK_INDEX_SHA256,
  liteIndexSha256: pin,
  rigSha256: rig.sha256,
  packs: report,
  triangles: report.reduce((sum, pack) => sum + pack.triangles, 0),
  fullAssetBytes: indexBytes.length + rigBytes.length + report.reduce((sum, pack) => sum + pack.fullBytes, 0),
  liteAssetBytes: encoded.length + rigBytes.length + report.reduce((sum, pack) => sum + pack.liteBytes, 0),
  elapsedSeconds: (performance.now() - start) / 1000,
}, null, 2));
