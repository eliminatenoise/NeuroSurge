"""Export two fixed NeuroTranslate 0.0 tasks for browser inference."""

import argparse
from base64 import b64encode
from hashlib import sha256
import json
from pathlib import Path

import numpy as np


CHECKPOINT = "f58dec8857015d84962aeb00259badf71b42d9bf7105cec35851a87826ed57d6"
ARCHITECTURE = {"depth": 1, "ff_width": 64, "heads": 4, "width": 32}
TASKS = {"landmark_motion": (5, 8, 2), "rat_next_unit": (1, 5, 1)}


def expected_shapes():
    yield "trunk.null", (32,)
    for name in ("q", "k", "v", "proj", "ln1", "ff1", "ff2", "ln2"):
        size = (64, 32) if name == "ff1" else (32, 64) if name == "ff2" else (32, 32)
        yield f"trunk.{name}.weight", (32,) if name in ("ln1", "ln2") else size
        yield f"trunk.{name}.bias", (size[0],)
    for task, (_, channels, outputs) in TASKS.items():
        yield f"adapters.{task}.weight", (32, channels * 2)
        yield f"adapters.{task}.bias", (32,)
        yield f"outputs.{task}.weight", (outputs, 32)
        yield f"outputs.{task}.bias", (outputs,)
        yield f"{task}.xmean", (channels,)
        yield f"{task}.xscale", (channels,)
        if task == "landmark_motion":
            yield f"{task}.ymean", (outputs,)
            yield f"{task}.yscale", (outputs,)


def render(checkpoint):
    if sha256(checkpoint.read_bytes()).hexdigest() != CHECKPOINT:
        raise ValueError("Use the published NeuroTranslate 0.0 joint alpha checkpoint.")
    tensors = {}
    with np.load(checkpoint, allow_pickle=False) as archive:
        if json.loads(str(archive["architecture"])) != ARCHITECTURE:
            raise ValueError("The browser uses the published one-block architecture.")
        schemas = json.loads(str(archive["schemas"]))
        for task, (steps, channels, outputs) in TASKS.items():
            spec = schemas[task]
            if (spec["history_steps"], len(spec["channels"]), len(spec["outputs"])) != (steps, channels, outputs):
                raise ValueError(f"Unexpected schema for {task}.")
        for name, shape in expected_shapes():
            values = archive[name]
            if values.shape != shape or values.dtype != np.dtype("float32") or not np.isfinite(values).all():
                raise ValueError(f"Unexpected tensor {name}.")
            tensors[name] = b64encode(values.astype("<f4", copy=False).tobytes()).decode("ascii")
    lines = [
        "// Generated by tools/export-browser-forecast.py from the published NeuroTranslate 0.0 checkpoint.",
        "// The tensor bytes and attribution are described in NOTICE.html.",
        f"export const checkpointSha256 = {json.dumps(CHECKPOINT)};",
        "export const tensors = " + json.dumps(tensors, indent=2) + ";",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkpoint", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(render(args.checkpoint), encoding="utf-8")


if __name__ == "__main__":
    main()
