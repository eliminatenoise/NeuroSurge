"""Adapt a saved NeuroTranslate viewer to the game's script policy. No dependencies or downloads."""
import base64
import hashlib
import json
from pathlib import Path
import re
import sys

ASSETS = Path(__file__).resolve().parents[1] / "scene/src/activity/shared-motion"
CHECKPOINTS = (
    "9a3649cb8f2119984e7f9f0b96a07bdc95e1833c7068f0e9caef2680f22e3179",
    "da243393b7a6f72558365a30f7361e45ef7af680538a7fb5a927e930d91b3458",
)
RUNTIME = "529d37c72208cbb699197839a160fe34360a9ee3339b8417b7d908df0a8e1b0c"
VIEWER = "d25e15f73a4f0f3e70f61045f6dfe68275b8d8b5367987faa6b48a6bb737110f"

def pack():
    source = (ASSETS / "index.html").read_bytes()
    if hashlib.sha256(source).hexdigest() != VIEWER:
        sys.exit("Viewer checksum differs from the release pin.")
    html = source.decode("utf-8")
    scripts = re.findall(r"<script>(.*?)</script>", html, flags=re.S)
    if (len(scripts) != 2 or any(pin not in html for pin in CHECKPOINTS)
            or hashlib.sha256(scripts[0].encode()).hexdigest() != RUNTIME):
        sys.exit("Unexpected viewer layout, checkpoint or runtime.")
    for script, name in zip(scripts, ("shared-motion.js", "panel.js"), strict=True):
        raw = script.encode("utf-8")
        if name == "panel.js":
            # Async weight verification can still be pending at the frame load event.
            # The host needs to distinguish this from a missing or rejected UI script.
            raw += b'\ndocument.currentScript.dataset.started = "true";\n'
        (ASSETS / name).write_bytes(raw)
        integrity = base64.b64encode(hashlib.sha256(raw).digest()).decode("ascii")
        html = html.replace("<script>" + script + "</script>",
                            f'<script src="@@ASSETS@@/{name}" integrity="sha256-{integrity}"></script>', 1)
    # The original remains a complete offline download. The embedded copy permits only
    # same-origin external scripts and keeps connect-src 'none', including during inference.
    replacements = {
        "script-src 'unsafe-inline'": "script-src 'self'",
        # A narrow game frame includes another set of margins outside the viewer.
        "</style>": """@media(max-width:319px) {
  main {width:100%}
  .experiment {padding-inline:.25rem}
  .angle-table {table-layout:auto}
  .angle-table th:first-child {width:auto}
  .angle-table th,.angle-table td {padding-inline:.12rem}
}
</style>""",
        '<a class="save" href="" download=': '<a class="save" href="@@ASSETS@@/index.html" download=',
        'rel="noreferrer"': 'target="_blank" rel="noopener noreferrer"',
    }
    for before, after in replacements.items():
        if before not in html:
            sys.exit(f"Missing expected upstream markup: {before}")
        html = html.replace(before, after)
    encoded = json.dumps(html, ensure_ascii=False)
    (ASSETS / "document.mjs").write_text(
        "// Generated by tools/pack-shared-motion.py from the adjacent frozen index.html.\n"
        + "export const viewerDocument = " + encoded + ";\n", encoding="utf-8")

if __name__ == "__main__":
    pack()
